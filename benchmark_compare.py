# Automatically detect all character files
# ------------------------------------------------------------
files = [f for f in os.listdir(DATA_PATH) if f.endswith(".json")]

print("Detected files:", files)

all_results = {}

for file in files:

    results = run_character_experiment(file)

    all_results[file.replace(".json","")] = results